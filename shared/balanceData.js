export function normalizeQuestion(q) {
  if (!q) return null;
  return {
    ...q,
    prompt: q.title,
    option_a: q.optionA,
    option_b: q.optionB,
  };
}

export function getQuestionById(id) {
  const q = BALANCE_QUESTIONS.find((item) => item.id === id);
  return normalizeQuestion(q);
}

/** Next question in feed — skip already voted (localStorage keys) */
export function pickNextUnvoted(votedIds = [], afterId = null) {
  const voted = new Set(votedIds);
  const startIdx = afterId
    ? BALANCE_QUESTIONS.findIndex((q) => q.id === afterId) + 1
    : 0;

  for (let i = startIdx; i < BALANCE_QUESTIONS.length; i += 1) {
    if (!voted.has(BALANCE_QUESTIONS[i].id)) {
      return normalizeQuestion(BALANCE_QUESTIONS[i]);
    }
  }
  for (let i = 0; i < startIdx; i += 1) {
    if (!voted.has(BALANCE_QUESTIONS[i].id)) {
      return normalizeQuestion(BALANCE_QUESTIONS[i]);
    }
  }
  return normalizeQuestion(BALANCE_QUESTIONS[0]);
}

export function pickRandomQuestion(excludeIds = []) {
  const exclude = new Set(excludeIds);
  const pool = BALANCE_QUESTIONS.filter((q) => !exclude.has(q.id));
  const list = pool.length ? pool : BALANCE_QUESTIONS;
  return normalizeQuestion(list[Math.floor(Math.random() * list.length)]);
}

export function getQuestionProgress(questionId) {
  const idx = BALANCE_QUESTIONS.findIndex((q) => q.id === questionId);
  return {
    current: idx >= 0 ? idx + 1 : 1,
    total: BALANCE_QUESTIONS.length,
  };
}

/** Parse share link choice: A/B/a/b → 'a' | 'b' */
export function parseSharedChoice(raw) {
  if (!raw) return null;
  const c = String(raw).toUpperCase();
  if (c === 'A') return 'a';
  if (c === 'B') return 'b';
  return null;
}

export function buildShareUrl(questionId, choice) {
  const side = choice === 'a' ? 'A' : 'B';
  const base = typeof window !== 'undefined' ? window.location.origin : 'https://nambac.xyz';
  return `${base}/balance?q=${encodeURIComponent(questionId)}&voted=${side}`;
}
